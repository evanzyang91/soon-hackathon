export interface PlanInput {
  prompt: string;
  scene: SceneContext;
  selection?: Selection;
  view?: ViewInfo;
  /** Offline keyword planner (MOCK=1 / no key). */
  mock: boolean;
  log?: (m: string) => void;
  /** Prefix for new op ids (tests). */
  idPrefix?: string;
  /** Test seams. */
  call?: PlannerCall;
  locateCall?: LocateCall;
}

export interface PlanResult {
  plan: EditPlan;
  /** Pixel boxes of named objects in the view (normalised), for ops listed in needsTarget. */
  targets: TargetBox[];
  source: 'claude' | 'mock';
  notes: string[];
  usage: { input: number; output: number; costUsd: number };
}

export type PlannerCall = (req: {
  system: string;
  content: string;
  schema: Record<string, unknown>;
}) => Promise<Anthropic.Beta.BetaMessage>;

const defaultCall: PlannerCall = async ({ system, content, schema }) => {
  const client = new Anthropic({ apiKey: env.keys.anthropic });
  const stream = client.beta.messages.stream({
    model: PLANNER_MODEL,
    max_tokens: PLANNER_MAX_TOKENS,
    // a policy decline is retried on the default fallback model
    betas: ['server-side-fallback-2026-07-01'],
    fallbacks: 'default',
    thinking: { type: 'adaptive' },
    output_config: { effort: 'low', format: { type: 'json_schema', schema } },
    system: [{ type: 'text', text: system, cache_control: { type: 'ephemeral' } }],
    messages: [{ role: 'user', content }],
  });
  return stream.finalMessage();
};

const r2 = (v: number) => Math.round(v * 100) / 100;
const fmt = (v: readonly number[]) => `(${v.map(r2).join(', ')})`;

/** The scene as the planner sees it (plain text; stable order). */
export function describeScene(scene: SceneContext, o: { selection?: Selection; view?: ViewInfo } = {}): string {
  const lines: string[] = [];
  const w = scene.world;
  lines.push(`Scene: ${scene.plan.heading} (${w.interior ? 'interior' : 'exterior'}, ${w.timeOfDay}).`);
  lines.push(`World prompt: ${w.prompt.slice(0, 700)}`);
  if (w.caption && w.caption !== w.prompt) lines.push(`World caption: ${w.caption.slice(0, 400)}`);
  lines.push(
    w.panoUrl
      ? 'The world panorama is available (a world-regen of sky/weather/season can edit it: pano-inpaint).'
      : 'No world panorama (a world-regen would use a new text prompt).',
  );
  const cam = o.view?.position ?? [0, 1.6, 0];
  const axes = cameraAxes(o.view?.quaternion);
  lines.push(
    `Director's camera at ${fmt(cam)}; on the floor plane it looks along ${fmt([axes.forward[0], 0, axes.forward[1]])}, its right is ${fmt([axes.right[0], 0, axes.right[1]])}. World frame: metres, Y up, floor y = 0, the world's source camera at the origin looking down -Z.`,
  );
  lines.push('Actors (id, name, position, yaw deg, scale):');
  for (const a of scene.actors)
    lines.push(`- ${a.id} "${a.name}" at ${fmt(a.position)}, yaw ${Math.round((a.yaw * 180) / Math.PI)}°, scale ${r2(a.scale)}, ${a.pose}`);
  if (!scene.actors.length) lines.push('- none');
  lines.push('Props (id, kind, label, position):');
  for (const p of scene.props)
    lines.push(`- ${p.id} ${p.kind} "${p.label}" ${p.moving ? 'moving, path starts' : 'parked'} at ${fmt(p.position)}${p.added ? ' (added by an edit)' : ''}`);
  if (!scene.props.length) lines.push('- none');
  const def = defaultLook() as Record<string, unknown>;
  const look = scene.look as unknown as Record<string, unknown>;
  const changed = Object.keys(look)
    .filter((k) => k !== 'lights' && JSON.stringify(look[k]) !== JSON.stringify(def[k]))
    .map((k) => `${k}=${JSON.stringify(look[k])}`);
  lines.push(`Current look: ${changed.length ? changed.join(', ') : 'neutral (all defaults)'}.`);
  lines.push('Look lights (id, name, kind, position):');
  for (const l of scene.lights) lines.push(`- ${l.id} "${l.name}" ${l.kind} at ${fmt(l.position)} ${l.color} ×${l.intensity}`);
  if (!scene.lights.length) lines.push('- none');
  const enabled = scene.edits.edits.filter((e) => e.enabled);
  if (enabled.length)
    lines.push(
      `Edits already applied: ${enabled.map((e) => (e.kind === 'splat-region' ? `region "${e.label}"` : e.kind === 'transform' ? `move ${e.target.id}` : e.kind)).join(', ')}.`,
    );
  if (o.selection?.region)
    lines.push(`The director has selected a ${o.selection.region.shape} region at ${fmt(o.selection.region.center)} (the object the prompt is about).`);
  else if (o.selection?.point) lines.push(`The director clicked the point ${fmt(o.selection.point)} in the world.`);
  else lines.push('Nothing is selected in the viewport.');
  return lines.join('\n');
}

export function plannerUserText(prompt: string, scene: SceneContext, o: { selection?: Selection; view?: ViewInfo } = {}): string {
  return `${describeScene(scene, o)}\n\nDirector's prompt: """${prompt.trim().slice(0, 600)}"""\n\nReturn the edit plan.`;
}

/** prompt + scene → EditPlan (+ vision targets for unresolved regions when a view is attached). */
export async function planEdit(input: PlanInput): Promise<PlanResult> {
  const log = input.log ?? (() => {});
  const prompt = input.prompt.trim();
  if (!prompt) throw new Error('prompt is empty');
  const offline = input.mock || (!env.keys.anthropic && !input.call);
  let draft: Draft;
  let usage = { input: 0, output: 0, costUsd: 0 };
  if (offline) {
    draft = mockDraft(prompt, input.scene, { selection: input.selection, viewQuaternion: input.view?.quaternion });
  } else {
    const schema = betaZodOutputFormat(Draft).schema as Record<string, unknown>;
    const t0 = Date.now();
    const msg = await (input.call ?? defaultCall)({
      system: PLANNER_SYSTEM,
      content: plannerUserText(prompt, input.scene, input),
      schema,
    });
    usage = costOf(msg.usage);
    log(
      `planner ${PLANNER_MODEL}: ${msg.stop_reason} in ${((Date.now() - t0) / 1000).toFixed(1)}s (in ${usage.input} / out ${usage.output} tokens, ~$${usage.costUsd.toFixed(4)})`,
    );
    if (msg.stop_reason === 'refusal') throw new Error('Claude declined to plan this edit');
    if (msg.stop_reason === 'max_tokens') throw new Error('the edit plan was cut off (max_tokens)');
    const text = msg.content.flatMap((b) => (b.type === 'text' ? [b.text] : [])).join('');
    draft = Draft.parse(JSON.parse(text));
  }
  const { plan, notes } = draftToPlan(draft, {
    prompt,
    scene: input.scene,
    selection: input.selection,
    idPrefix: input.idPrefix,
  });
  for (const n of notes) log(`plan: ${n}`);

  let targets: TargetBox[] = [];
  if (plan.needsTarget.length && input.view?.image) {
    if (offline) {
      notes.push('offline planner: no vision targets; click the object');
    } else {
      try {
        const r = await locateObjects(input.view.image, plan.needsTarget, { call: input.locateCall, log });
        targets = r.targets;
        usage = {
          input: usage.input + r.usage.input,
          output: usage.output + r.usage.output,
          costUsd: usage.costUsd + r.usage.costUsd,
        };
        const missing = plan.needsTarget.filter((t) => !targets.some((x) => x.opId === t.opId));
        if (missing.length) notes.push(`vision did not find: ${missing.map((m) => m.label).join(', ')}`);
      } catch (e) {
        notes.push(`vision targeting failed: ${(e as Error).message}`);
        log(`vision targeting failed: ${(e as Error).message}`);
      }
    }
  }
  return { plan, targets, source: offline ? 'mock' : 'claude', notes, usage };
}
